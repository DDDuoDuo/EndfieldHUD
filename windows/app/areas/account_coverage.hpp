// In-process community host behind the production signed client: answers the
// fixed read-only endpoints on the two community API hosts with the fixture
// envelopes (one-shot scripted overrides first) and rejects anything else.
// Completions run only in drain(), on the owner thread, never inside start().
class SyntheticCommunityHost final : public native::OwnerDrainedAccountTransport {
public:
    using Response = AccountCoverageFixture::Response;
    explicit SyntheticCommunityHost(std::map<std::string, Response, std::less<>> routes);
    modules::hypergryph::RequestHandle start(modules::hypergryph::HttpRequest, std::function<void(modules::hypergryph::HttpOutcome)>) override;
    void post(std::function<void()>) override;
    std::size_t drain() override;
    std::optional<double> nextDeadline() const override { return std::nullopt; }
    bool deadline(double) override { return false; }
    std::size_t activeRequests() const override { return inFlight_; }
    void script(std::string path, Response once);
    std::size_t queued() const noexcept { return queue_.size(); }
    const std::vector<modules::hypergryph::HttpRequest>& requests() const noexcept { return requests_; }
    void clearRequests() { requests_.clear(); }
    unsigned rejected() const noexcept { return rejected_; }

private:
    std::map<std::string, Response, std::less<>> routes_;
    std::map<std::string, std::deque<Response>, std::less<>> scripted_;
    std::deque<std::function<void()>> queue_;
    std::vector<modules::hypergryph::HttpRequest> requests_;
    std::size_t inFlight_{};
    unsigned rejected_{};
};

// Avatar downloads never leave the process: every load completes unavailable.
class SyntheticAvatarLoader final : public modules::hypergryph::AccountAvatarLoader {
public:
    explicit SyntheticAvatarLoader(SyntheticCommunityHost& queue) : queue_(queue) {}
    modules::hypergryph::RequestHandle load(const std::string&, std::function<void(std::optional<std::vector<std::uint8_t>>)>) override;
    unsigned loads() const noexcept { return loads_; }

private:
    SyntheticCommunityHost& queue_;
    unsigned loads_{};
};

// Fake official-site host in place of the WebView2 window: present() opens a
// real LoginSession with the fixture nonce (as the presenter does after
// Connect); coverage then drives consent, the navigation / popup / bridge
// message fixture through the session's policy and finishes it. Completions
// are posted to the owner queue like the presenter's finish message.
class SyntheticLoginHost final : public modules::hypergryph::AccountLoginPresenter {
public:
    using Completion = std::function<void(std::optional<modules::hypergryph::LoginResult>, modules::hypergryph::LoginFailure)>;
    SyntheticLoginHost(SyntheticCommunityHost& queue, std::string nonce) : queue_(queue), nonce_(std::move(nonce)) {}
    void present(modules::hypergryph::Region, Completion) override;
    void cancel() override;
    bool isPresenting() const override { return session_ && session_->presenting(); }
    modules::hypergryph::LoginSession* session() noexcept { return isPresenting() ? &*session_ : nullptr; }
    // Ends the presented session (completed / cancelled / expired) and posts
    // the controller completion; false when nothing is presented.
    bool finish(std::optional<modules::hypergryph::LoginResult>, modules::hypergryph::LoginFailure);
    unsigned presentations() const noexcept { return presentations_; }
    const std::vector<std::string>& diagnostics() const noexcept { return diagnostics_; }

private:
    SyntheticCommunityHost& queue_;
    std::string nonce_;
    std::optional<modules::hypergryph::LoginSession> session_;
    Completion completion_;
    unsigned presentations_{};
    std::vector<std::string> diagnostics_; // last finished session's fixed tags
};
